"""Command line interface for synthetic-only ResearchReplicator workflows."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

from .compare import compare_records
from .extract import extract_file
from .fixtures import create_fixtures
from .io import RepkitError, json_text, read_json, write_json, write_text
from .plan import build_plan
from .report import render_html, render_markdown
from .schema import HONESTY_BOUNDARY
from .tracker import run_fixture, track_config


HONESTY = f"HONESTY BOUNDARY: {HONESTY_BOUNDARY} run invokes a hash-pinned deterministic CPU metric emitter only."


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="repkit",
        description="Extract, plan, track, and compare declared synthetic research fixtures.",
        epilog=HONESTY,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--version", action="version", version="repkit 0.1.0")
    sub = parser.add_subparsers(dest="command", required=True)

    fixtures = sub.add_parser("fixtures", help="write deterministic fictional paper and repo fixtures")
    fixtures.add_argument("--out", required=True, help="directory for the generated synthetic fixtures")

    extract = sub.add_parser("extract", help="extract a typed setup record from a fixture Markdown paper")
    extract.add_argument("paper", help="synthetic Markdown paper path")
    extract.add_argument("--out", default="-", help="JSON output path, or - for stdout")
    extract.add_argument("--state-dir", help="also store setup.json in this workflow directory")

    plan = sub.add_parser("plan", help="build an ordered reproduction plan from a setup JSON record")
    plan.add_argument("setup", help="setup JSON path from extract")
    plan.add_argument("--out", default="-", help="JSON output path, or - for stdout")
    plan.add_argument("--state-dir", help="also store plan.json in this workflow directory")

    track = sub.add_parser("track", help="snapshot a JSON config and record its diff from the previous config")
    track.add_argument("--config", required=True, help="JSON config file to track")
    track.add_argument("--reason", default="manual update", help="reason for this config version")
    track.add_argument("--state-dir", default=".repkit", help="workflow state directory")

    run = sub.add_parser(
        "run",
        help="run a hash-pinned synthetic CPU metric emitter from a declared fixture repo; no model training",
        description="Run only the deterministic synthetic CPU metric emitter generated by repkit fixtures. This does not train a model.",
        epilog=HONESTY,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    run.add_argument("--config", required=True, help="tracked config id, for example cfg-012345abcdef")
    run.add_argument("--repo", required=True, help="directory generated by repkit fixtures")
    run.add_argument("--script", default="train.py", help="fixture entrypoint, only train.py is supported")
    run.add_argument("--state-dir", default=".repkit", help="workflow state directory")

    compare = sub.add_parser("compare", help="compare declared paper results with observed synthetic metrics")
    compare.add_argument("paper_results", help="setup JSON with reported_results")
    compare.add_argument("observed", help="run JSON with metrics")
    compare.add_argument("--out", default="-", help="JSON output path, or - for stdout")
    compare.add_argument("--state-dir", help="also store comparison.json in this workflow directory")

    report = sub.add_parser("report", help="assemble setup, plan, config history, comparison, and provenance")
    report.add_argument("--format", choices=("md", "html"), default="md", help="report format")
    report.add_argument("--state-dir", default=".repkit", help="workflow state directory")
    report.add_argument("--out", help="report path; defaults to report.md or report.html in state directory")
    return parser


def _emit(value: Any, output: str) -> None:
    content = json_text(value)
    if output == "-":
        sys.stdout.write(content)
    else:
        write_text(output, content)
        print(f"Wrote {output}")


def main(argv: list[str] | None = None) -> int:
    parser = _parser()
    args = parser.parse_args(argv)
    try:
        if args.command == "fixtures":
            print(json_text({"honesty": HONESTY_BOUNDARY, "files": create_fixtures(args.out)}), end="")
        elif args.command == "extract":
            setup = extract_file(args.paper)
            if args.state_dir:
                write_json(Path(args.state_dir) / "setup.json", setup)
            _emit(setup, args.out)
        elif args.command == "plan":
            setup = read_json(args.setup)
            plan = build_plan(setup)
            if args.state_dir:
                write_json(Path(args.state_dir) / "plan.json", plan)
            _emit(plan, args.out)
        elif args.command == "track":
            print(json_text(track_config(args.config, args.state_dir, args.reason)), end="")
        elif args.command == "run":
            print(json_text(run_fixture(args.config, args.repo, args.state_dir, args.script)), end="")
        elif args.command == "compare":
            result = compare_records(read_json(args.paper_results), read_json(args.observed))
            if args.state_dir:
                write_json(Path(args.state_dir) / "comparison.json", result)
            _emit(result, args.out)
        elif args.command == "report":
            content = render_markdown(args.state_dir) if args.format == "md" else render_html(args.state_dir)
            output = args.out or str(Path(args.state_dir) / f"report.{args.format}")
            if output == "-":
                sys.stdout.write(content)
            else:
                write_text(output, content)
                print(f"Wrote {output}")
        return 0
    except RepkitError as exc:
        print(f"repkit: error: {exc}", file=sys.stderr)
        return 2
    except (OSError, KeyError, TypeError, ValueError) as exc:
        print(f"repkit: error: {exc}", file=sys.stderr)
        return 2
